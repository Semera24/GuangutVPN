"""Linux Kernel Security Layer: nftables Kill Switch, IPv6 Leak Blocker & DNS Guard."""

from __future__ import annotations
import os
import shutil
import subprocess
from typing import Optional

NFT_TABLE_NAME = "guangut_killswitch"
RESOLV_BACKUP = "/var/tmp/guangut.resolv.conf.bak"


def _run_root(argv: list[str]) -> subprocess.CompletedProcess:
    if os.geteuid() == 0:
        return subprocess.run(argv, capture_output=True, text=True)
    return subprocess.run(["sudo", "-n"] + argv, capture_output=True, text=True)


def enable_killswitch(vpn_server_ip: str, vpn_iface: str = "tun+") -> tuple[bool, str]:
    """Enable an nftables kernel firewall table that blocks non-VPN outbound traffic and IPv6 leaks."""
    nft_bin = shutil.which("nft") or "/usr/sbin/nft"
    if not os.path.exists(nft_bin):
        return False, "nftables binary (/usr/sbin/nft) not found"

    # First remove any stale table
    _run_root([nft_bin, "delete", "table", "inet", NFT_TABLE_NAME])

    rules = f"""
table inet {NFT_TABLE_NAME} {{
    chain output {{
        type filter hook output priority 0; policy drop;
        oifname "lo" accept
        ct state established,related accept
        ip daddr {vpn_server_ip} accept
        ip daddr 127.0.0.0/8 accept
        ip daddr 10.0.0.0/8 accept
        ip daddr 172.16.0.0/12 accept
        ip daddr 192.168.0.0/16 accept
        oifname "{vpn_iface}" accept
        oifname "wg+" accept
    }}
}}
"""
    proc = subprocess.run(
        ([nft_bin, "-f", "-"] if os.geteuid() == 0 else ["sudo", "-n", nft_bin, "-f", "-"]),
        input=rules,
        capture_output=True,
        text=True,
    )
    if proc.returncode != 0:
        return False, f"Failed to load nftables kill switch: {proc.stderr.strip()}"
    return True, f"nftables Kill Switch active (table inet {NFT_TABLE_NAME})"


def disable_killswitch() -> bool:
    """Remove the GuangutVPN nftables Kill Switch table."""
    nft_bin = shutil.which("nft") or "/usr/sbin/nft"
    if not os.path.exists(nft_bin):
        return False
    res = _run_root([nft_bin, "delete", "table", "inet", NFT_TABLE_NAME])
    return res.returncode == 0


def is_killswitch_active() -> bool:
    nft_bin = shutil.which("nft") or "/usr/sbin/nft"
    if not os.path.exists(nft_bin):
        return False
    res = _run_root([nft_bin, "list", "table", "inet", NFT_TABLE_NAME])
    return res.returncode == 0


def configure_tunnel_dns(iface: str = "tun0", dns_servers: tuple[str, str] = ("1.1.1.1", "8.8.8.8")) -> str:
    """Configure leak-free DNS for the active VPN interface via resolvectl or /etc/resolv.conf."""
    resolvectl = shutil.which("resolvectl")
    if resolvectl:
        r1 = _run_root([resolvectl, "dns", iface, *dns_servers])
        r2 = _run_root([resolvectl, "domain", iface, "~."])
        if r1.returncode == 0 and r2.returncode == 0:
            return f"systemd-resolved configured on {iface} ({', '.join(dns_servers)})"

    # Fallback: if /etc/resolv.conf is not managed by systemd-resolved stub
    try:
        if os.path.exists("/etc/resolv.conf") and not os.path.exists(RESOLV_BACKUP):
            _run_root(["cp", "-f", "/etc/resolv.conf", RESOLV_BACKUP])
        content = "# Generated by GuangutVPN (DNS Leak Guard)\n" + "".join(
            f"nameserver {ip}\n" for ip in dns_servers
        )
        tmp_resolv = "/tmp/guangut.resolv.conf"
        with open(tmp_resolv, "w", encoding="utf-8") as f:
            f.write(content)
        _run_root(["cp", "-f", tmp_resolv, "/etc/resolv.conf"])
        return f"/etc/resolv.conf locked to {', '.join(dns_servers)}"
    except OSError as exc:
        return f"DNS fallback warning: {exc}"


def restore_system_dns() -> None:
    """Restore original /etc/resolv.conf if a backup was taken."""
    if os.path.exists(RESOLV_BACKUP):
        _run_root(["mv", "-f", RESOLV_BACKUP, "/etc/resolv.conf"])

